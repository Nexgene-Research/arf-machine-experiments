"""Derive dated v2 exclusion reasons from the bounded ten-row v1 table.

The historical genome-wide results/exclusions.tsv is not regenerated by this
bounded script; see docs/manual_steps.md for missing source-stage lineage.
"""

from __future__ import annotations

import csv
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
INPUT = ROOT / "results/track1_top10_ranked.tsv"
OUT = ROOT / "results/track1/v2_exclusions.tsv"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--primary-counts", type=Path)
    parser.add_argument("--out", type=Path)
    args = parser.parse_args()
    if args.primary_counts is not None:
        if args.out is None or args.out.exists():
            raise ValueError("new output path required and must not already exist")
        primary = json.loads(args.primary_counts.read_text())
        with (ROOT / "results/track1/top10_reconstructed.tsv").open(newline="") as fh:
            selected_genes = {r["gene"] for r in csv.DictReader(fh, delimiter="\t")}
        epcr = json.loads((ROOT / "results/track1/epcr_summary.json").read_text())
        lexical_nonselected = list(
            dict.fromkeys(g for g in epcr["top_genes"] if g not in selected_genes)
        )
        rows = []

        def add(gene, kind, n, reason):
            rows.append((gene, kind, n, reason, "no"))

        for gene, n in primary["tier1_pair_counts"].items():
            if gene not in selected_genes:
                add(
                    gene,
                    "compound_het",
                    n,
                    "not among ten read-backed selected hypotheses; phase not established",
                )
            elif gene == "MAD1L1":
                add(
                    gene,
                    "compound_het",
                    n,
                    "many combinatorial pairs; selected read-backed rows require separate adjudication",
                )
        for gene in lexical_nonselected:
            add(
                gene,
                "compound_het",
                "lex_top10_pad",
                "appeared in full-rank top ten, not in read-backed top ten",
            )
        for gene, n in primary["tier1_homozygous_counts"].items():
            add(
                gene,
                "homozygous",
                n,
                "not selected by read-backed compound-het top-ten filter",
            )
        if (
            primary["read_stage"]["published"] != 4
            or primary["read_stage"]["published_sites_pileup_alt"] != 0
        ):
            raise ValueError(
                "published-site aggregate not as expected; do not infer individual counts"
            )
        # Producer script track1_reads.py records these four public site IDs.
        # Four nonnegative pileup counts with a sum of zero are each zero.
        for name in (
            "published_BUB1B_chr15_40117088",
            "published_BUB1_chr2_110677994",
            "published_TRIP13_chr5_914504",
            "published_TRIP13_chr5_907987",
        ):
            add(
                name,
                "published_snv",
                1,
                "ALT pileup zero on original read stage (zero sum over four sites)",
            )
        add(
            "non_tier1_het_pair_genes",
            "compound_het",
            primary["non_tier1_pair_genes"],
            "distinct non-Tier-1 genes with passing pairs in full hypotheses; not equivalent to number of excluded rows",
        )
        with args.out.open("w", newline="") as fh:
            writer = csv.writer(fh, delimiter="\t", lineterminator="\n")
            writer.writerow(("gene", "hypothesis_class", "n", "reason", "submitted"))
            writer.writerows(rows)
        print(
            f"aggregate_exclusions={len(rows)} non_tier1_pair_genes={primary['non_tier1_pair_genes']}"
        )
        return
    if OUT.exists():
        raise FileExistsError(OUT)
    with INPUT.open(newline="", encoding="utf-8") as fh:
        candidates = list(csv.DictReader(fh, delimiter="\t"))
    rows = []
    for row in candidates:
        key = ";".join(
            f"{row[f'chrom_{n}']}:{row[f'pos_{n}']}:{row[f'ref_{n}']}:{row[f'alt_{n}']}"
            for n in (1, 2)
        )
        high_af = [
            n
            for n in (1, 2)
            if row[f"gnomad_af_{n}"] and float(row[f"gnomad_af_{n}"]) > 0.01
        ]
        if high_af:
            reason = "recessive second allele AF>0.01; no documented founder exception"
            status = "exclude"
        elif all(
            "intron" in row[f"consequence_{n}"] or "upstream" in row[f"consequence_{n}"]
            for n in (1, 2)
        ):
            reason = "no established damaging allele mechanism at either site"
            status = "exclude"
        elif any("intron" in row[f"consequence_{n}"] for n in (1, 2)):
            reason = "intronic second-allele mechanism not verified; retain only if new evidence establishes it"
            status = "conditional"
        else:
            reason = "read, phase and missense molecular effect require v2 adjudication"
            status = "conditional"
        rows.append(
            (row["gene"], key, status, reason, "results/track1_top10_ranked.tsv")
        )
    with OUT.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.writer(fh, delimiter="\t", lineterminator="\n")
        writer.writerow(("gene", "grch38_pair", "v2_status", "reason", "source"))
        writer.writerows(rows)
    print(
        f"v2 exclusions reviewed {len(rows)} legacy rows; excluded {sum(r[2] == 'exclude' for r in rows)}; conditional {sum(r[2] == 'conditional' for r in rows)}"
    )


if __name__ == "__main__":
    main()
